def auc(pos, neg):
    # plain rank AUC, ties count half. n is tiny so no need for sklearn here
    pos, neg = np.asarray(pos), np.asarray(neg)
    return float(((pos[:, None] > neg[None, :]).sum()
                  + 0.5 * (pos[:, None] == neg[None, :]).sum()) / (len(pos) * len(neg)))

